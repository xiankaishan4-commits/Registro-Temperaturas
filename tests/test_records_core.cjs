const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../app/src/main/assets/records-core.js'),'utf8');
const context={};vm.createContext(context);vm.runInContext(source,context);
const U=context.RTRecords;
const at=(date)=>new Date(date).getTime();
const devices=[{id:'d1',nombre:'EXKAL 01'},{id:'d2',nombre:'AHT 01'}];
const original={id:'a',equipoId:'d1',equipoNombre:'EXKAL 01',temperatura:3.1,timestamp:at('2026-10-20T09:10:00'),fecha:'2026-10-20'};
const revision={...original,id:'b',registroTipo:'correction',supersedesId:'a',temperatura:3.2,recordedAt:at('2026-10-21T11:00:00')};
const late={id:'c',equipoId:'d2',equipoNombre:'AHT 01',temperatura:-18.7,timestamp:at('2026-10-20T21:30:00'),registroTipo:'late',recordedAt:at('2026-10-21T10:00:00')};
const missed={id:'z',equipoId:'d1',equipoNombre:'EXKAL 01',temperatura:null,timestamp:at('2026-10-19T21:00:00'),fecha:'2026-10-19',registroTipo:'omitted',slotProgramado:'2026-10-19/21'};
assert.equal(U.isMeasurement(missed),false);
assert.equal(U.isMeasurement(late),true);
assert.equal(U.effective([original,revision,late]).length,2);
assert.equal(U.slotKey(original.timestamp),'2026-10-20/09');
assert.equal(U.slotKey(late.timestamp),'2026-10-20/21');
assert(U.slotSatisfied([original,revision], 'd1', '2026-10-20/09'));
assert(!U.slotSatisfied([missed], 'd1', '2026-10-19/21'));
const rows=U.exportRows([original,revision,late,missed],devices);
assert.equal(rows.length,3);
assert.equal(rows.find(x=>x.equipo==='EXKAL 01'&&x.temperatura).temperatura,'3,2');
assert.equal(rows.find(x=>x.equipo==='AHT 01').hora,'21:30');
const omission=rows.find(x=>x.fecha==='2026-10-19');
assert.equal(omission.hora,'');assert.equal(omission.temperatura,'');
assert.equal(U.exportRows([original,revision,late,missed],devices,{deviceId:'d1',from:'2026-10-20',to:'2026-10-20'}).length,1);
const csv=U.csv(rows);
assert(csv.includes('Equipo;')===false); // CSV uses quoted values
assert(csv.includes('"Equipo";"Fecha de medición";"Hora de medición"'));
assert(!csv.includes('Registro tardío'));
assert(csv.includes('"-18,7"'));
assert(U.csv([{equipo:'=HYPERLINK("evil")',fecha:'',hora:'',temperatura:'',responsable:'',observaciones:''}]).includes("'="));
console.log('Record core: 16 checks passed');
