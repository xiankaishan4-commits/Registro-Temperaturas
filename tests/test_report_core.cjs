const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const code = fs.readFileSync(path.join(__dirname, '../app/src/main/assets/report-core.js'), 'utf8');
const ctx = { atob: x => Buffer.from(x, 'base64').toString('binary') };
vm.createContext(ctx); vm.runInContext(code, ctx);
const R = ctx.RTReports;
const photo = 'data:image/jpeg;base64,' + Buffer.from([0xFF,0xD8,0xFF,0xD9]).toString('base64');
const row = {id:'r1',equipo:'Mural 1 Carnes',fecha:'2026-10-21',hora:'09:12',temperatura:'2,5',responsable:'Ana',observaciones:'',foto:photo};
const report = R.packageReport([row], {from:'2026-10-21',to:'2026-10-21',equipoNombre:'Mural 1 Carnes'});
assert.equal(report.length,2);
const manifest = JSON.parse(report[0].data);
assert.equal(manifest.format, 'SHANFOODSGROUP_PDF_REPORT_V1');
assert.equal(manifest.rows[0].equipo, 'Mural 1 Carnes');
assert.equal(manifest.rows[0].fotoArchivo, report[1].name);
assert.equal(report[1].data[0],0xff);
assert.equal(manifest.rows[0].fecha,'2026-10-21');
assert.equal(manifest.rows[0].hora,'09:12');
assert.equal(manifest.rows[0].temperatura,'2,5');
assert(!JSON.stringify(manifest).includes('/9j/'));
assert(!JSON.stringify(manifest).includes('Registro tardío'));
assert.throws(()=>R.packageReport([]),/No hay/);
assert.throws(()=>R.packageReport(Array(181).fill(row)),/180/);
assert.throws(()=>R.packageReport([{...row,foto:'data:text/html;base64,SGVsbG8='}]),/Formato/);
const omission = R.packageReport([{id:'missed',equipo:'AHT 2',fecha:'2026-10-21',hora:'',temperatura:'',foto:null,observaciones:'Sin medición'}]);
assert.equal(omission.length,1);
assert.equal(JSON.parse(omission[0].data).rows[0].hora,'');
console.log('PDF report packaging: 14 validations passed');
